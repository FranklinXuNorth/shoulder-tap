/**
 * 聊天里的两只手。
 *
 * 桌面悬浮窗暂时不做 —— 在能盖住别的应用之前，敲在终端里的手你看不见，
 * 那个假设还没被验证。所以介入先全部走聊天：该停的时候，把这只手打出来。
 *
 * 这是服务端唯一「生成内容」的地方，而它生成的是一张画，不是你的数据。
 */
/** taptap：食指点三下。跑偏了、习惯到点了，用它。 */
const HAND = [
    "                 tap tap",
    "       __________       |",
    "  ____/  ________/)   .  |",
    " /      (___            |",
    "|       (___)           |",
    " \\______(__)            |",
].join("\n");
/** 响指：拇指和中指一捻，这一轮做完了。跟桌面上一轮做完打的响指是同一个意思。 */
const SNAP = [
    "                 snap",
    "             \\  |  /",
    "         ___   ` `",
    "   _____/   )__",
    "  /      (_____)  *",
    " |       (___)",
    "  \\______(__)",
].join("\n");
/** 真跑偏了：手 + 一句点破 + 一个问题，然后停住。 */
export function offTaskBanner() {
    return ["```", HAND, "```"].join("\n");
}
/**
 * 到点的习惯用同一只手，但**不在当下打断**。
 * 见 protocolText：等当前这条做完，或者做到一半有自然停顿时才带出来。
 */
export function dueBanner() {
    return offTaskBanner();
}
/** 做完了：响指。跟 taptap 同一轮都要打的话，响指在前，各自一个代码块。 */
export function doneBanner() {
    return ["```", SNAP, "```"].join("\n");
}
export { HAND, SNAP };
